/** A tool's title, icon and kind for the timeline. */
export function metaFor(name = 'write_note'): {
  title: string;
  icon: typeof Wrench;
  kind: ToolKind;
} {
  return { ...(shown[name] ?? { title: name, icon: Wrench }), kind: kindOf(name) };
}
